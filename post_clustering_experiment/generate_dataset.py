# Synthesize variations to create 150 realistic pairs
all_pairs = []
all_pairs.extend(duplicate_seeds)
all_pairs.extend(non_duplicate_seeds)

# Augment with variations
prefix_templates = ["แจ้งปัญหาครับ: ", "ขอร้องเรียนหน่อยค่ะ ", "ช่วยประสานงานให้ทีครับ ", "ด่วนมาก! ", ""]
