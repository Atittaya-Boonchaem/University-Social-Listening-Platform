for s1, s2, is_dup, score, cat in duplicate_seeds:
    p1 = random.choice(prefix_templates) + s1 + random.choice(suffix_templates)
    p2 = random.choice(prefix_templates) + s2 + random.choice(suffix_templates)
    adj_score = max(0.70, min(0.99, score + random.uniform(-0.04, 0.04)))
    all_pairs.append((p1, p2, 1, round(adj_score, 2), cat))

for s1, s2, is_dup, score, cat in non_duplicate_seeds:
    p1 = random.choice(prefix_templates) + s1 + random.choice(suffix_templates)
    p2 = random.choice(prefix_templates) + s2 + random.choice(suffix_templates)
    adj_score = max(0.01, min(0.48, score + random.uniform(-0.03, 0.03)))
    all_pairs.append((p1, p2, 0, round(adj_score, 2), cat))

