def save_datasets():
    train_path = os.path.join(DATA_DIR, "train_pairs.json")
    test_path = os.path.join(DATA_DIR, "test_pairs.json")

    with open(train_path, "w", encoding="utf-8") as f:
        json.dump(TRAIN_DATA, f, ensure_ascii=False, indent=2)

    with open(test_path, "w", encoding="utf-8") as f:
        json.dump(TEST_DATA, f, ensure_ascii=False, indent=2)

    print(f"Generated Training Samples: {len(TRAIN_DATA)} pairs -> {train_path}")
    print(f"Generated Evaluation Samples: {len(TEST_DATA)} pairs -> {test_path}")

if __name__ == "__main__":
    save_datasets()
