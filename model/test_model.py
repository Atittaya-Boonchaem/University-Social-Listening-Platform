import pandas as pd

# 1. โหลดข้อมูล 1,500 ข้อ (ที่มีเฉลย Actual_Category แล้ว)
print("กำลังโหลดชุดข้อมูล 1,500 ข้อ...")
df_test = pd.read_csv("test_dataset_1500.csv")

# 2. คลังความรู้ (Rule-based) ที่เราอัปเดตล่าสุด
category_rules = {
    "สิ่งอำนวยความสะดวกและอาคารสถานที่": ["พัง", "ชำรุด", "ประตูพัง", "หลังคารั่ว", "ไฟดับ", "น้ำไม่ไหล", "แอร์ไม่เย็น", "ลิฟต์ค้าง", "หลอดไฟขาด", "แอร์", "ประปา", "ลิฟต์"],
    "ระบบเครือข่ายและเทคโนโลยี": ["เน็ตหลุด", "ไวไฟเข้าไม่ได้", "เน็ตช้า", "หลุดบ่อย", "ระบบล่ม", "เข้าเว็บไม่ได้", "ลืมรหัสผ่าน", "ลงทะเบียนไม่ได้", "ระบบ"],
    "ความปลอดภัยและจราจร": ["รถชน", "ขโมย", "อันตราย", "รปภ.", "รถติด", "จอดรถขวาง", "ทางมืด", "เปลี่ยว", "ไม่มีไฟกิ่ง", "รปภ"],
    "สุขอนามัยและความสะอาด": ["สกปรก", "ขยะล้น", "เหม็น", "ถังขยะเต็ม", "ไม่ทำความสะอาด", "หญ้ารก", "กิ่งไม้หัก", "ต้นไม้ล้ม", "หมาจรจัด", "ทำความสะอาด"],
    "การเรียนการสอนและหลักสูตร": ["ตารางเรียน", "วันสอบ", "เกรด", "หน่วยกิต", "วิชา", "ดรอปเรียน", "ติดต่ออาจารย์", "ขอสอบชดเชย", "อาจารย์"],
    "การเดินทางและระบบขนส่ง": ["รถเมล์", "รถเมล์มอ", "รถมอ", "รถไฟฟ้า", "รอรถ", "รอนาน", "รถเต็ม", "ป้ายรถเมล์", "คิวรถ", "ตารางรถ", "สายรถ", "ท่ารถ", "ไม่จอดรับ"],
    "บริการและสวัสดิการนิสิต": ["ทุนการศึกษา", "กิจกรรม", "บัตรนิสิต", "สอบถามหน่อยครับ", "ขอคำแนะนำ", "อยากทราบว่า", "ของหาย", "หมวกกันน็อคหาย", "หมวกกันน็อกหาย", "ลืมของ", "ลืมหมวกกันน็อก", "ตามหาของ"]
}

# 3. ฟังก์ชันการจัดหมวดหมู่
def analyze_text(text):
    if not isinstance(text, str):
        text = str(text)
    scores = {cat: 0 for cat in category_rules}
    for category, keywords in category_rules.items():
        for kw in keywords:
            if kw in text:
                scores[category] += 1
                
    max_score = max(scores.values())
    if max_score == 0:
        return "บริการและสวัสดิการนิสิต"
    else:
        return max(scores, key=scores.get)

# 4. สั่งให้ระบบทำข้อสอบ
print("ให้ระบบอ่านข้อความดิบ และจัดหมวดหมู่...")
df_test['Predicted_Category'] = df_test['Raw_Text'].apply(analyze_text)

# 5. ตรวจคำตอบเทียบกับเฉลย (Actual_Category)
df_test['Is_Correct'] = df_test['Actual_Category'] == df_test['Predicted_Category']
accuracy = (df_test['Is_Correct'].sum() / len(df_test)) * 100

print("\n========================================")
print(" สรุปผลความแม่นยำ (จากข้อสอบ 1,500 ข้อ)")
print("========================================")
print(f" ความแม่นยำ: {accuracy:.2f}%")
print(f" ทายถูก: {df_test['Is_Correct'].sum()} ข้อ")
print(f" ทายผิด: {len(df_test) - df_test['Is_Correct'].sum()} ข้อ")
print("========================================\n")

# ---------------------------------------------------------
# 6. คัดแยกและบันทึกข้อที่ระบบทายผิด
# ---------------------------------------------------------
print(" กำลังดึงข้อที่ระบบทายผิด...")

# คัดกรองเฉพาะแถวที่ Is_Correct เป็น False (ทายผิด)
wrong_answers = df_test[df_test['Is_Correct'] == False]

# แสดงตัวอย่าง 5 ข้อแรกที่ทายผิดในหน้าจอ Terminal
print("\n--- ตัวอย่าง 5 ข้อที่ระบบทายพลาด ---")
print(wrong_answers[['Raw_Text', 'Actual_Category', 'Predicted_Category']].head(5))
print("------------------------------------\n")

# บันทึกข้อที่ผิดทั้งหมด (57 ข้อ) ลงไฟล์ CSV เพื่อให้เปิดดูใน Excel ได้ง่ายๆ
wrong_answers.to_csv("wrong_predictions.csv", index=False, encoding="utf-8-sig")

print("บันทึกข้อที่ผิดทั้งหมดลงไฟล์ 'wrong_predictions.csv' เรียบร้อยแล้วครับ!")

# ---------------------------------------------------------
# 7. เจาะลึกดูเฉพาะข้อที่ผิดพลาดใน "บริการและสวัสดิการนิสิต"
# ---------------------------------------------------------
print("\n🔍 กำลังวิเคราะห์ข้อที่ผิดพลาดเฉพาะบริการและสวัสดิการนิสิต...")

# ใช้ df_test ตัวเดิมได้เลย ไม่ต้องโหลดไฟล์ใหม่
other_errors = wrong_answers[
    (wrong_answers['Actual_Category'] == 'บริการและสวัสดิการนิสิต') | 
    (wrong_answers['Predicted_Category'] == 'บริการและสวัสดิการนิสิต')
]

print(f"จำนวนข้อที่ผิดพลาดเกี่ยวกับหมวดบริการทั่วไป/อื่นๆ: {len(other_errors)} ข้อ")
print(other_errors[['Raw_Text', 'Actual_Category', 'Predicted_Category']].head(10))